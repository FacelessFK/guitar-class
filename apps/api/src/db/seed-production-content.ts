const ARTICLE_SLUG_PATTERN = /^[^/\\.\s%]+$/u;
const CLASSICAL_GUITAR_SLUG = "classical-guitar";
const SEED_LOCK_KEY = "music-platform:production-article-content-v1";

export interface SeedProductionContentOptions {
  authorPhone: string;
  apply: boolean;
}

export interface SeedProductionContentResult {
  mode: "dry-run" | "applied";
  authorName: string;
  existing: number;
  inserted: number;
  wouldInsert: number;
}

export function validateArticleManifest(
  articles: readonly ProductionArticle[] = PRODUCTION_ARTICLES,
): void {
  if (articles.length !== 5) {
    throw new Error(`seed تولید باید دقیقاً ۵ نوشته داشته باشد؛ مقدار فعلی ${articles.length} است.`);
  }

  const slugs = new Set<string>();

  for (const article of articles) {
    if (!article.slug || article.slug.length > 200 || !ARTICLE_SLUG_PATTERN.test(article.slug)) {
      throw new Error(`اسلاگ نوشتهٔ seed نامعتبر است: ${article.slug || "<خالی>"}`);
    }
    if (slugs.has(article.slug)) {
      throw new Error(`اسلاگ تکراری در خود seed: ${article.slug}`);
    }
    slugs.add(article.slug);

    if (!article.title.trim() || article.title.length > 200) {
      throw new Error(`عنوان نوشتهٔ «${article.slug}» نامعتبر است.`);
    }
    if (!article.excerpt.trim() || article.excerpt.length > 500) {
      throw new Error(`خلاصهٔ نوشتهٔ «${article.slug}» نامعتبر است.`);
    }
    if (!article.content.trim() || article.content.length > 100_000) {
      throw new Error(`متن نوشتهٔ «${article.slug}» نامعتبر است.`);
    }
    if (
      article.status !== "PUBLISHED" ||
      article.coverUrl !== null ||
      article.coverObjectKey !== null
    ) {
      throw new Error(`وضعیت انتشار یا تصویر نوشتهٔ «${article.slug}» با قرارداد seed سازگار نیست.`);
    }
  }
}

export function parseSeedArguments(args: readonly string[]): SeedProductionContentOptions {
  let authorPhone: string | undefined;
  let apply = false;

  for (let index = 0; index < args.length; index += 1) {
    const argument = args[index];

    if (argument === "--apply") {
      apply = true;
      continue;
    }

    if (argument === "--author-phone") {
      const value = args[index + 1];
      if (!value || value.startsWith("--")) {
        throw new Error("بعد از --author-phone باید شمارهٔ موبایل نویسنده بیاید.");
      }
      if (authorPhone !== undefined) {
        throw new Error("--author-phone نباید بیشتر از یک بار فرستاده شود.");
      }
      authorPhone = value;
      index += 1;
      continue;
    }

    throw new Error(`آرگومان ناشناخته: ${argument}`);
  }

  if (!authorPhone) {
    throw new Error(
      "استفاده: pnpm db:seed:content -- --author-phone <شماره> [--apply]\n" +
        "بدون --apply فقط dry-run انجام می‌شود.",
    );
  }

  const normalized = normalizePhone(authorPhone);
  if (!normalized) {
    throw new Error("شمارهٔ موبایل نویسنده معتبر نیست.");
  }

  return { authorPhone: normalized, apply };
}

export async function seedProductionContent(
  options: SeedProductionContentOptions,
): Promise<SeedProductionContentResult> {
  validateArticleManifest();

  const authorPhone = normalizePhone(options.authorPhone);
  if (!authorPhone) throw new Error("شمارهٔ موبایل نویسنده معتبر نیست.");

  return db.transaction(async (tx) => {
    // دو اجرای هم‌زمان نباید هر دو از preflight عبور کنند و سر unique
    // constraint به هم برسند. قفل فقط تا پایان همین تراکنش نگه داشته می‌شود.
    await tx.execute(sql`SELECT pg_advisory_xact_lock(hashtext(${SEED_LOCK_KEY}))`);

    const [author] = await tx
      .select({
        id: users.id,
        fullName: users.fullName,
        status: users.status,
        isAdmin: users.isAdmin,
      })
      .from(users)
      .where(eq(users.phone, authorPhone))
      .limit(1);

    if (!author) {
      throw new Error("کاربر نویسنده پیدا نشد؛ seed هیچ کاربری ایجاد نمی‌کند.");
    }
    if (author.status !== "ACTIVE" || !author.isAdmin) {
      throw new Error("نویسنده باید یک کاربر موجود، فعال و دارای دسترسی ادمین باشد.");
    }

    const [instrument] = await tx
      .select({ id: instruments.id, isActive: instruments.isActive })
      .from(instruments)
      .where(eq(instruments.slug, CLASSICAL_GUITAR_SLUG))
      .limit(1);

    if (!instrument) {
      throw new Error("ساز classical-guitar پیدا نشد؛ seed هیچ سازی ایجاد نمی‌کند.");
    }
    if (!instrument.isActive) {
      throw new Error("ساز classical-guitar غیرفعال است؛ seed آن را خودکار فعال نمی‌کند.");
    }

    const articleBySlug = new Map(PRODUCTION_ARTICLES.map((article) => [article.slug, article]));
    const existingRows = await tx
      .select({
        slug: posts.slug,
        title: posts.title,
        excerpt: posts.excerpt,
        content: posts.content,
        coverUrl: posts.coverUrl,
        coverObjectKey: posts.coverObjectKey,
        instrumentId: posts.instrumentId,
        authorId: posts.authorId,
        status: posts.status,
        publishedAt: posts.publishedAt,
      })
      .from(posts)
      .where(inArray(posts.slug, [...articleBySlug.keys()]));

    const conflicts = existingRows.filter((row) => {
      const article = articleBySlug.get(row.slug)!;
      return (
        row.title !== article.title ||
        row.excerpt !== article.excerpt ||
        row.content !== article.content ||
        row.coverUrl !== null ||
        row.coverObjectKey !== null ||
        row.instrumentId !== instrument.id ||
        row.authorId !== author.id ||
        row.status !== "PUBLISHED" ||
        row.publishedAt === null
      );
    });

    if (conflicts.length > 0) {
      throw new Error(
        "تعارض slug با نوشتهٔ موجود؛ هیچ تغییری اعمال نشد: " +
          conflicts.map((row) => row.slug).join("، "),
      );
    }

    const existingSlugs = new Set(existingRows.map((row) => row.slug));
    const missing = PRODUCTION_ARTICLES.filter((article) => !existingSlugs.has(article.slug));

    if (options.apply && missing.length > 0) {
      const publishedAt = new Date();
      await tx.insert(posts).values(
        missing.map((article) => ({
          slug: article.slug,
          title: article.title,
          excerpt: article.excerpt,
          content: article.content,
          coverUrl: article.coverUrl,
          coverObjectKey: article.coverObjectKey,
          instrumentId: instrument.id,
          authorId: author.id,
          status: article.status,
          publishedAt,
        })),
      );
    }

    return {
      mode: options.apply ? "applied" : "dry-run",
      authorName: author.fullName,
      existing: existingRows.length,
      inserted: options.apply ? missing.length : 0,
      wouldInsert: missing.length,
    };
  });
}

