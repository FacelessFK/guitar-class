/**
 * صفحه‌بندی فهرست‌های پنل ادمین.
 *
 * سقف ثابتِ ۲۰۰ سطر مسئله را پنهان می‌کرد نه حل: تا دویست رزرو همه‌چیز
 * درست به نظر می‌رسید و بعد از آن، ادمین بی‌آنکه بفهمد فقط تازه‌ترین‌ها
 * را می‌دید — بی‌هیچ نشانه‌ای که چیزی جا مانده. بدترین شکل خرابی، همانی
 * است که شبیه کارِ درست است.
 *
 * `offset` است و نه cursor. برای پنل ادمین درست است چون «صفحه‌ی ۳» معنا
 * دارد و باید بشود مستقیم رفت سراغش؛ بهایش این است که با درج هم‌زمان،
 * یک سطر می‌تواند بین دو صفحه جابه‌جا شود. برای گزارشی که چند بار در روز
 * باز می‌شود قابل قبول است، و راه‌حلش — cursor — «برو به صفحه‌ی آخر» را
 * از بین می‌برد.
 *
 * فهرست‌هایی که با **اندازه‌ی کاتالوگ** بزرگ می‌شوند (سازها، استادها)
 * صفحه‌بندی ندارند: تعدادشان از مرتبه‌ی ده‌هاست و ادمین همه را با هم
 * می‌خواهد. این ماژول برای فهرست‌هایی است که با هر رزرو و هر پرداخت
 * رشد می‌کنند.
 */

export interface PageQuery {
  limit?: number;
  offset?: number;
}

export interface Page<T> {
  rows: T[];
  /**
   * کل سطرهای منطبق با فیلتر، نه طول این صفحه.
   *
   * بدون آن، فرانت نمی‌داند صفحه‌ی بعدی وجود دارد یا نه — و همان ابهامی
   * می‌شود که سقف ثابت داشت.
   */
  total: number;
  limit: number;
  offset: number;
}

export const PAGE_SIZE = 50;
export const MAX_PAGE_SIZE = 200;

/**
 * ورودی کلاینت را به بازه‌ی امن می‌برد.
 *
 * سقف بالا لازم است چون `limit` از کوئری می‌آید: بدون آن، یک درخواست با
 * `limit=1000000` کل جدول را می‌خواند و حافظه‌ی پروسه را می‌بلعد.
 */
export function pageBounds(query: PageQuery): { limit: number; offset: number } {
  return {
    limit: Math.min(Math.max(query.limit ?? PAGE_SIZE, 1), MAX_PAGE_SIZE),
    offset: Math.max(query.offset ?? 0, 0),
  };
}
