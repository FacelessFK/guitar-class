/**
 * ریشه‌ی خطاهای دامنه.
 *
 * پیام‌ها فارسی و مستقیماً قابل نمایش به کاربرند، ولی `code` ماشین‌خوان
 * است تا لایه‌ی بالاتر بتواند بدون تکیه بر متن تصمیم بگیرد.
 *
 * دلیل وجود یک ریشه‌ی مشترک: یک فیلتر خطا در لایه‌ی HTTP همه را
 * می‌گیرد. اگر هر دامنه ریشه‌ی خودش را داشت، اضافه کردن دامنه‌ی جدید
 * یعنی یادت برود فیلترش را ثبت کنی و خطای قابل‌فهمِ کاربر به ۵۰۰ تبدیل
 * شود.
 */
export class DomainError extends Error {
  constructor(
    message: string,
    readonly code: string,
  ) {
    super(message);
    this.name = new.target.name;
  }
}
