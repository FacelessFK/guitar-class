-- قیدهای یکپارچگی رزرو
--
-- این مایگریشن دست‌نویس است چون `EXCLUDE USING gist` را هیچ ORMـی در
-- زبان اسکیمای خودش بیان نمی‌کند. با Drizzle این یک راه فرار نیست —
-- مایگریشن سفارشی جزو جریان عادی کار است و درست کنار مایگریشن‌های
-- تولیدشده می‌نشیند و در همان تاریخچه ردیابی می‌شود.
--
-- بقیه‌ی قیدهای CHECK پروژه در خود تعریف جدول‌ها (src/db/schema) هستند
-- و به‌صورت خودکار تولید می‌شوند.

-- btree_gist اجازه می‌دهد ستون برابری‌محور (uuid) و ستون بازه‌ای را در
-- یک ایندکس GiST کنار هم بگذاریم.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------------
-- ۱. پایان جلسه همیشه با طول جلسه بخواند
-- ---------------------------------------------------------------------------
-- `ends_at` ستون ذخیره‌شده است، نه محاسبه‌ای. دلیلش قید بعدی است: ایندکس
-- فقط عبارت IMMUTABLE می‌پذیرد و `timestamptz + interval` در پستگرس
-- STABLE است، چون نتیجه‌اش می‌تواند به تنظیم منطقه‌ی زمانی وابسته باشد.
--
-- این CHECK نگهبان آن ستون است. برخلاف ایندکس، CHECK عبارت STABLE را
-- می‌پذیرد. پس ناسازگاری با خطا رد می‌شود، نه اینکه بی‌صدا اصلاح شود.
ALTER TABLE "bookings"
  ADD CONSTRAINT "bookings_ends_at_consistent"
  CHECK ("ends_at" = "scheduled_at" + make_interval(mins => "duration_minutes"));

-- ---------------------------------------------------------------------------
-- ۲. یک استاد نمی‌تواند دو جلسه‌ی هم‌زمان داشته باشد
-- ---------------------------------------------------------------------------
-- ضامن اصلی سیستم رزرو.
--
-- بررسی تداخل در کد اپلیکیشن همیشه شرط رقابتی دارد: دو نفر هم‌زمان یک
-- اسلات را می‌زنند، هر دو کوئری «آزاد است؟» را می‌بینند، هر دو موفق
-- می‌شوند. این قید آن حالت را از نظر فیزیکی ناممکن می‌کند.
--
-- بازه‌ها نیم‌باز [start, end) هستند، پس جلسه‌ی ۱۶–۱۷ و جلسه‌ی ۱۷–۱۸
-- تداخل حساب نمی‌شوند.
--
-- شرط WHERE باید همیشه با SLOT_OCCUPYING_STATUSES در
-- packages/shared/src/enums.ts یکی بماند. رزرو لغوشده یا منقضی‌شده
-- اسلات را آزاد می‌کند.
ALTER TABLE "bookings"
  ADD CONSTRAINT "bookings_no_teacher_overlap"
  EXCLUDE USING gist (
    "teacher_id" WITH =,
    tstzrange("scheduled_at", "ends_at") WITH &&
  )
  WHERE ("status" IN ('PENDING_PAYMENT', 'CONFIRMED', 'IN_PROGRESS'));

-- ---------------------------------------------------------------------------
-- ۳. یک هنرجو هم نمی‌تواند دو کلاس هم‌زمان داشته باشد
-- ---------------------------------------------------------------------------
-- حالت واقعی: هنرجو با دو استاد مختلف تصادفاً یک ساعت را رزرو می‌کند.
ALTER TABLE "bookings"
  ADD CONSTRAINT "bookings_no_student_overlap"
  EXCLUDE USING gist (
    "student_id" WITH =,
    tstzrange("scheduled_at", "ends_at") WITH &&
  )
  WHERE ("status" IN ('PENDING_PAYMENT', 'CONFIRMED', 'IN_PROGRESS'));
