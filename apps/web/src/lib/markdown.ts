import { marked } from "marked";

/**
 * رندر مارک‌داون نوشته‌های بلاگ.
 *
 * **فقط در زمان بیلد اجرا می‌شود.** صفحات بلاگ SSG هستند، پس `marked`
 * هرگز به باندل مرورگر نمی‌رود — همان دلیلی که آوردن یک وابستگی اینجا
 * قابل قبول است ولی برای تقویم شمسی نبود: آن یکی در مرورگر اجرا می‌شد
 * و کاربر ایرانی روی اینترنت کند هزینه‌اش را می‌داد.
 *
 * ⚠️ **خروجی پاک‌سازی نمی‌شود.** محتوا فقط از پنل ادمین می‌آید و ادمین
 * از قبل به تغییر قیمت و داده‌ی مالی دسترسی دارد؛ HTML دلخواه چیزی به
 * دسترسی‌اش اضافه نمی‌کند. اگر روزی نوشتن به کسِ دیگری باز شود — استاد
 * مهمان، نویسنده‌ی بیرونی — این تصمیم **باید** بازبینی شود، چون آن وقت
 * یک `<script>` در متن نوشته روی دامنه‌ی اصلی اجرا می‌شود.
 */
export function renderMarkdown(content: string): string {
  return marked.parse(content, {
    // `async: false` صریح است تا تایپ خروجی رشته بماند نه Promise
    async: false,
    /**
     * شکست خط تکی، `<br>` می‌شود.
     *
     * نویسنده‌ی فارسی‌زبان در یک textarea می‌نویسد و انتظار دارد
     * Enter خط تازه بسازد. رفتار استاندارد مارک‌داون — که خط تکی را
     * نادیده می‌گیرد — در آن بافت شبیه باگ به نظر می‌رسد.
     */
    breaks: true,
    gfm: true,
  });
}

/**
 * زمان تقریبی مطالعه، به دقیقه.
 *
 * سرعت پایین‌تری از انگلیسی گرفته شده: متن فارسی در وب معمولاً کندتر
 * خوانده می‌شود و عددی که کمتر از واقعیت باشد، خواننده را وسط راه
 * غافلگیر می‌کند.
 */
export function readingMinutes(content: string): number {
  const words = content.trim().split(/\s+/u).length;
  return Math.max(1, Math.round(words / 180));
}
